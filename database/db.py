def save_quiz(
    quiz_id: str,
    topic: str,
    questions: List[Dict[str, Any]],
    answer_keys: List[Dict[str, Any]],
    db_path: Optional[str] = None
) -> None:
    """Persist generated quiz and its answer key."""
    conn = get_connection(db_path)
    with conn:
        conn.execute(
            """
            INSERT INTO quizzes (quiz_id, topic, questions_json, answer_keys_json)
            VALUES (?, ?, ?, ?);
            """,
            (
                quiz_id.strip(),
                topic.strip().lower(),
                json.dumps(questions),
                json.dumps(answer_keys)
            )
        )
    conn.close()


def get_quiz_by_id(quiz_id: str, db_path: Optional[str] = None) -> Optional[Dict[str, Any]]:
    """Retrieve quiz questions and answer keys by unique quiz ID."""
    conn = get_connection(db_path)
    cursor = conn.cursor()
    cursor.execute(
        "SELECT quiz_id, topic, questions_json, answer_keys_json FROM quizzes WHERE quiz_id = ?;",
        (quiz_id.strip(),)
    )
    row = cursor.fetchone()
    conn.close()

    if not row:
        return None

    return {
        "quiz_id": row["quiz_id"],
        "topic": row["topic"],
        "questions": json.loads(row["questions_json"]),
        "answer_keys": json.loads(row["answer_keys_json"])
    }


def save_attempt(
    quiz_id: str,
    topic: str,
    score: int,
    total_questions: int,
    submitted_answers: List[str],
    evaluations: List[Dict[str, Any]],
    db_path: Optional[str] = None
) -> int:
    """Save user quiz attempt and return new attempt ID."""
    conn = get_connection(db_path)
    with conn:
        cursor = conn.execute(
            """
            INSERT INTO quiz_attempts (
                quiz_id, topic, score, total_questions, submitted_answers_json, evaluations_json
            ) VALUES (?, ?, ?, ?, ?, ?);
            """,
            (
                quiz_id.strip(),
                topic.strip().lower(),
                score,
                total_questions,
                json.dumps(submitted_answers),
                json.dumps(evaluations)
            )
        )
        attempt_id = cursor.lastrowid
    conn.close()
    return attempt_id


def get_topic_analytics(topic: Optional[str] = None, db_path: Optional[str] = None) -> List[Dict[str, Any]]:
    """Aggregate total attempts and average score grouped by topic."""
    conn = get_connection(db_path)
    cursor = conn.cursor()

    if topic:
        cursor.execute(
            """
            SELECT 
                topic, 
                COUNT(*) as attempts_count,
                ROUND(AVG(CAST(score AS FLOAT) / total_questions * 100), 1) as avg_pct_score,
                MAX(score) as best_score,
                MAX(attempted_at) as last_attempted
            FROM quiz_attempts
            WHERE topic = ?
            GROUP BY topic;
            """,
            (topic.strip().lower(),)
        )
    else:
        cursor.execute(
            """
            SELECT 
                topic, 
                COUNT(*) as attempts_count,
                ROUND(AVG(CAST(score AS FLOAT) / total_questions * 100), 1) as avg_pct_score,
                MAX(score) as best_score,
                MAX(attempted_at) as last_attempted
            FROM quiz_attempts
            GROUP BY topic
            ORDER BY avg_pct_score ASC;
            """
        )

    rows = cursor.fetchall()
    conn.close()
    return [dict(r) for r in rows]


def save_study_plan(
    topics: List[str],
    available_minutes: int,
    days: int,
    schedule: List[Dict[str, Any]],
    db_path: Optional[str] = None
) -> int:
    """Persist generated revision study plan."""
    conn = get_connection(db_path)
    with conn:
        cursor = conn.execute(
            """
            INSERT INTO study_plans (topics_json, available_minutes_per_day, days, plan_schedule_json)
            VALUES (?, ?, ?, ?);
            """,
            (
                json.dumps(topics),
                available_minutes,
                days,
                json.dumps(schedule)
            )
        )
        plan_id = cursor.lastrowid
    conn.close()
    return plan_id


def get_latest_study_plan(db_path: Optional[str] = None) -> Optional[Dict[str, Any]]:
    """Retrieve most recently created active study plan."""
    conn = get_connection(db_path)
    cursor = conn.cursor()
    cursor.execute(
        """
        SELECT plan_id, topics_json, available_minutes_per_day, days, plan_schedule_json, created_at
        FROM study_plans 
        WHERE status = 'active'
        ORDER BY plan_id DESC LIMIT 1;
        """
    )
    row = cursor.fetchone()
    conn.close()

    if not row:
        return None

    return {
        "plan_id": row["plan_id"],
        "topics": json.loads(row["topics_json"]),
        "available_minutes_per_day": row["available_minutes_per_day"],
        "days": row["days"],
        "schedule": json.loads(row["plan_schedule_json"]),
        "created_at": row["created_at"]
    }