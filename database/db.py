"""
database/db.py - SQLite persistence layer for StudyBuddy AI.
Manages connection pooling, schema migrations, and parameterized queries.
"""
import sqlite3
import json
from datetime import datetime
from typing import Any, Dict, List, Optional
from config import DB_PATH


def get_connection(db_path: Optional[str] = None) -> sqlite3.Connection:
    """Return an SQLite connection configured with Row factory and foreign keys."""
    target_path = db_path if db_path is not None else str(DB_PATH)
    conn = sqlite3.connect(target_path)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON;")
    return conn


def init_db(db_path: Optional[str] = None) -> None:
    """Initialize relational tables if they do not already exist."""
    conn = get_connection(db_path)
    cursor = conn.cursor()

    # Table 1: Quizzes (Question content and secret answer keys)
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS quizzes (
            quiz_id TEXT PRIMARY KEY,
            topic TEXT NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            questions_json TEXT NOT NULL,
            answer_keys_json TEXT NOT NULL
        );
    """)

    # Table 2: Quiz Attempts (User submissions, scores, and feedback)
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS quiz_attempts (
            attempt_id INTEGER PRIMARY KEY AUTOINCREMENT,
            quiz_id TEXT NOT NULL,
            topic TEXT NOT NULL,
            score INTEGER NOT NULL,
            total_questions INTEGER NOT NULL,
            submitted_answers_json TEXT NOT NULL,
            evaluations_json TEXT NOT NULL,
            attempted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY(quiz_id) REFERENCES quizzes(quiz_id) ON DELETE CASCADE
        );
    """)

    # Table 3: Study Plans (Persisted schedules generated by agent)
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS study_plans (
            plan_id INTEGER PRIMARY KEY AUTOINCREMENT,
            topics_json TEXT NOT NULL,
            available_minutes_per_day INTEGER NOT NULL,
            days INTEGER NOT NULL,
            plan_schedule_json TEXT NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            status TEXT DEFAULT 'active'
        );
    """)

    # Indexes for rapid progress tracking queries
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_attempts_topic ON quiz_attempts(topic);")
    cursor.execute("CREATE INDEX IF NOT EXISTS idx_quizzes_topic ON quizzes(topic);")

    conn.commit()
    conn.close()


